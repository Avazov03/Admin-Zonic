def translit(s: str) -> str:
    out = []
    for ch in s:
        out.append(CYR.get(ch, ch))
    t = "".join(out)
    # Title-ish: first letter upper, rest lower for words
    parts = []
    for w in t.replace("_", " ").split():
        if not w:
            continue
        parts.append(w[0].upper() + w[1:].lower() if len(w) > 1 else w.upper())
    return " ".join(parts)


