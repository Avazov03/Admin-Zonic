for line in lines:
    cid, code, name = line.split("|", 2)
    code_n = str(int(code)) if code.isdigit() else code
    code_z = code.zfill(3) if code.isdigit() else code
    uz = BY_CODE.get(code_z) or BY_CODE.get(code_n) or translit(name)
    rows.append((int(cid), code_z, uz))

